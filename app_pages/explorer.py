import pandas as pd
import streamlit as st

from src.app_services import all_forward_nodes, history_nodes, summary_frame
from src.ui import csv_bytes, require_bundle


def _shipments(bundle):
    frames = []
    for result in bundle["results"].values():
        if result.shipments.empty:
            continue
        frame = result.shipments.loc[result.shipments["day"] >= 0].copy()
        if "policy" not in frame.columns:
            frame.insert(0, "policy", result.policy)
        else:
            ordered = ["policy", *[column for column in frame.columns if column != "policy"]]
            frame = frame[ordered]
        frames.append(frame)
    if not frames:
        return pd.DataFrame()
    return pd.concat(frames, ignore_index=True)


def _risk(bundle):
    frame = bundle["results"]["do_nothing"].risk.copy()
    return frame.loc[frame["day"] >= 0]

bundle = require_bundle()

st.title("Data explorer")
st.caption("All tables are generated by this run. Place names are labels, not a claim of real operations.")

catalog = bundle["catalog"]
sections = {
    "Suppliers": catalog["suppliers"],
    "Facilities": catalog["facilities"],
    "Retailer inventory": catalog["retailer_inventory"],
    "Baseline demand": catalog["baseline_demand"],
    "Routes": catalog["routes"],
    "Scenario event": bundle["events"],
    "Warm-up history": history_nodes(bundle),
    "Forward inventory": all_forward_nodes(bundle),
    "Shipments": _shipments(bundle),
    "Risk assessments": _risk(bundle),
    "Policy summary": summary_frame(bundle),
}

choice = st.selectbox("Table", list(sections))
frame = sections[choice]
if frame.empty:
    st.caption("This table is empty for the current run.")
else:
    st.dataframe(frame.head(400), width="stretch", hide_index=True)
    st.caption(f"{len(frame)} rows. The preview shows up to 400.")
    st.download_button(
        f"Download {choice}",
        data=csv_bytes(frame),
        file_name=f"echo_{choice.lower().replace(' ', '_')}.csv",
        mime="text/csv",
        icon=":material/download:",
    )
